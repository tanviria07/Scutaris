/**
 * Simplified world coastlines as `[longitude, latitude]` rings.
 *
 * Hand-authored for this project from general geographic knowledge, at roughly
 * 1-2 degree fidelity. This is deliberately *not* derived from Natural Earth,
 * GSHHG, OpenStreetMap or any other dataset, so there is no attribution or
 * licensing obligation attached to it and no asset to download. It is accurate
 * enough for continents to be recognisable on a globe and in the 2D fallback,
 * and nothing in the app depends on its precision.
 *
 * Longitude runs -180..180 (east positive), latitude -90..90 (north positive).
 * Rings are closed and are filled with a nonzero winding rule.
 */

export type Ring = readonly (readonly [number, number])[];

